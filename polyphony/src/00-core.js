/* =======================================================================
   Luce · модуль полифонии
   Идея представления: фуга — это ОДНА мысль, которую голоса передают друг
   другу. Поэтому главный слой картинки — не «где какая нота», а «кто
   сейчас говорит тему». Всё остальное (траектория, события, плотность)
   подчинено этому и приглушается, когда тема звучит.
   ======================================================================= */

const clamp=(v,a,b)=>v<a?a:v>b?b:v;
const lerp=(a,b,t)=>a+(b-a)*t;
