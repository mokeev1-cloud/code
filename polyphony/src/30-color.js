/* ---------- 4. цвет = высота. Шкала накала ----------
   Соответствие «выше звук — светлее» — самое устойчивое из кросс-модальных,
   поэтому шкала строго монотонна по светлоте. Физическая метафора, которую
   не надо объяснять, — накал: остывший пепел, вишнёвый, багровый, оранжевый,
   золото, белое каление. Через зелёный/бирюзовый не проходит ни в одной
   точке (та ошибка была в HSL-версии), золото остаётся якорем к плееру Luce. */
const RAMP=[
  [0.00,[ 12, 34, 84]],[0.16,[ 28, 62,132]],[0.34,[ 74, 84,124]],
  [0.52,[156, 74, 66]],[0.68,[196, 90, 48]],[0.84,[240,150, 54]],
  [0.94,[255,199, 92]],[1.00,[255,246,222]]
];
const norm=m=>clamp((m-LO)/(HI-LO),0,1);
function rampAt(x){
  for(let i=1;i<RAMP.length;i++){
    if(x<=RAMP[i][0]){
      const [x0,c0]=RAMP[i-1],[x1,c1]=RAMP[i],t=(x-x0)/(x1-x0);
      return [lerp(c0[0],c1[0],t),lerp(c0[1],c1[1],t),lerp(c0[2],c1[2],t)];
    }
  }
  return RAMP[RAMP.length-1][1];
}

/* Цвет ноты. Скрябин — историческая таблица его светового клавира; она
   разложена НЕ по хроматике, а по квинтовому кругу, и в этом её смысл:
   близкие по родству тоны получают близкие цвета. */
const SCRIABIN=[
  [255, 40, 40],[150, 60,235],[255,236, 70],[120,140,160],[150,205,255],[200, 30, 30],
  [ 60,100,255],[255,150, 45],[195,120,225],[ 80,220, 90],[140,150,170],[185,210,255]
];
/* Своя схема — обобщение той же идеи до правила: цветовое расстояние равно
   гармоническому. Кладём квинтовый круг на круг тона, тритон оказывается
   ровно напротив. Круг hue здесь оправдан (он и есть носитель смысла) —
   в отличие от шкалы высоты, где он давал грязь. */
function hsl2rgb(h,s,l){
  const a=s*Math.min(l,1-l);
  const f=n=>{const k=(n+h/30)%12;return l-a*Math.max(-1,Math.min(k-3,9-k,1));};
  return [f(0)*255,f(8)*255,f(4)*255];
}
const FIFTHS=[]; for(let pc=0;pc<12;pc++) FIFTHS[pc]=hsl2rgb((pc*7%12)*30,0.82,0.58);

const MODES=['высота','нота · Скрябин','нота · квинты'];
let MODE=1;
function noteRGB(midi){
  const pc=((midi%12)+12)%12;
  const base=MODE===0?rampAt(norm(midi)):(MODE===1?SCRIABIN[pc]:FIFTHS[pc]);
  if(MODE===0) return base;
  // регистр не теряем: тон задаёт цвет, высота — светлоту
  const k=0.45+norm(midi)*0.85;
  return [clamp(base[0]*k,0,255),clamp(base[1]*k,0,255),clamp(base[2]*k,0,255)];
}
function pitchColor(midi,bright,alpha){
  const c=noteRGB(midi);
  return `rgba(${lerp(c[0],255,bright*0.5)|0},${lerp(c[1],255,bright*0.5)|0},${lerp(c[2],255,bright*0.5)|0},${alpha})`;
}
