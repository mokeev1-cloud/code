"""
Подсчёт твёрдых и мягких форм прилагательного ДАЛЬНИЙ/ДАЛЬНЫЙ.

Твёрдая основа (архаичная, пушкинская, «через ы/о»):
    дальный, дальной, дальная, дальную, дальное, дальные, дальных,
    дальным, дальными, дальною, дального, дальному
Мягкая основа (современная норма, «через и/е»):
    дальний, дальней, дальняя, дальнюю, дальнее, дальние, дальних,
    дальним, дальними, дальнею, дальнего, дальнему

Запуск:
    python3 tools/dalny_forms.py corpus/pushkin/pushkin_10vol.txt corpus/ryzhy/*.txt

Результат (ноябрь 2026): Пушкин — 46 твёрдых / 42 мягких; Рыжий во всех
4 изданиях — 0 твёрдых. ОГОВОРКА: «дальной» формально может быть и
мягкой формой с опечаткой, а «без дальных слов/умыслов» у Пушкина значит
«лишних», а не «далёких» — такие случаи разбираются вручную (см. отчёт).
Счёт идёт по всему тексту, включая прозу, письма и комментарии издания.
"""
import collections
import re
import sys

HARD = r'дальн(ый|ой|ая|ую|ое|ые|ых|ым|ыми|ою|ого|ому)$'
SOFT = r'дальн(ий|ей|яя|юю|ее|ие|их|им|ими|ею|его|ему)$'

for p in sys.argv[1:]:
    t = open(p, encoding='utf-8').read().lower()
    # (?<![а-яё]) — граница слова слева: не ловим «отдальн…», «медальн…».
    c = collections.Counter(re.findall(r'(?<![а-яё])дальн[а-яё]*', t))
    hard = {k: v for k, v in c.items() if re.match(HARD, k)}
    soft = {k: v for k, v in c.items() if re.match(SOFT, k)}
    print(p,
          '\n  твёрдые', sum(hard.values()), hard,
          '\n  мягкие ', sum(soft.values()), soft)
